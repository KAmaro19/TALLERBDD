
SET SERVEROUTPUT ON;

DECLARE
    calificacion NUMBER := 85;

BEGIN
    --AQUI COLOCAMOS VARIOS ELSIF YA QUE SE REVISA LAS CALIFICACIONES PARA PODER SABER A QUE CONCUERDA CADA UNA 
    IF calificacion BETWEEN 70 AND 74 THEN
        DBMS_OUTPUT.PUT_LINE('Calificacion MALA');

    ELSIF calificacion BETWEEN 75 AND 84 THEN
        DBMS_OUTPUT.PUT_LINE('Calificacion BUENA');

    ELSIF calificacion BETWEEN 85 AND 100 THEN
        DBMS_OUTPUT.PUT_LINE('Calificacion EXCELENTE');

    ELSE
        DBMS_OUTPUT.PUT_LINE('Calificacion reprobable'); --EN ESTE CASO PUSIMOS EL ULTIMO ELSE PARA DETERMINAR QUE SI ES UNA CALIFICACION MENOR SERIA REPROBATORIA 
    END IF;
END;
